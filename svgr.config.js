// Generates typed react-native-svg components from assets/svg/icons (run `pnpm icons`).
// Each icon gets `size` (longest side, defaults to the Figma size) and `color` (fills `currentColor`).
const path = require('node:path');
// @babel/types comes with svgr; resolve it from there rather than adding a dependency.
const t = require(require.resolve('@babel/types', { paths: [require.resolve('@svgr/core')] }));

/** @type {import('@svgr/core').Config['template']} */
function template(variables, { tpl }) {
  const svg = variables.jsx.openingElement;
  const viewBox = svg.attributes.find((a) => a.name && a.name.name === 'viewBox').value.value;
  const [, , w, h] = viewBox.split(' ').map(Number);
  const name = t.identifier(`${variables.componentName.replace(/^Svg/, '')}Icon`);
  const [W, H, M] = [w, h, Math.max(w, h)].map((n) => t.numericLiteral(n));
  // Drop the unused `SvgProps` type import svgr adds in TypeScript mode.
  const imports = variables.imports.filter((i) => i.importKind !== 'type');
  return tpl`
${imports};
import type { IconProps } from './icon-props';

export function ${name}({ size = ${M}, color = 'white', ...props }: IconProps) {
  const width = (size * ${W}) / ${M};
  const height = (size * ${H}) / ${M};
  return ${variables.jsx};
}
`;
}

function indexTemplate(filePaths) {
  const lines = filePaths.map(({ path: p }) => {
    const base = path.basename(p, path.extname(p));
    const name = base.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
    return `export { ${name}Icon } from './${base}';`;
  });
  return `// Generated by \`pnpm icons\` — do not edit by hand.\nexport type { IconProps } from './icon-props';\n${lines.join('\n')}\n`;
}

module.exports = {
  native: true,
  typescript: true,
  dimensions: false,
  expandProps: 'end',
  svgProps: { width: '{width}', height: '{height}', color: '{color}' },
  jsxRuntime: 'automatic',
  // Keep Figma's paths verbatim; only strip the xmlns attribute react-native-svg ignores.
  svgoConfig: { plugins: ['removeXMLNS'] },
  prettier: true,
  prettierConfig: { singleQuote: true, printWidth: 100 },
  filenameCase: 'kebab',
  template,
  indexTemplate,
};
